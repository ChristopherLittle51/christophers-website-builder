import { chromium, firefox, webkit } from '@playwright/test';
import assert from 'node:assert/strict';
const origin = process.env.QA_ORIGIN || 'http://localhost:3010';
const sharedNavigation = process.env.QA_SHARED_NAVIGATION === '1';
const browserType = process.env.QA_BROWSER || 'chromium';
const browser = await ({ chromium, firefox, webkit }[browserType]).launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
let data = { root: { props: {} }, content: Array.from({ length: 60 }, (_, i) => ({ type: 'ParagraphBlock', props: { id: `paragraph-${i}`, name: `paragraph-${i}`, text: `Paragraph ${i}. Keep typing here.`, size: 'lead', width: 'normal', align: 'left' } })) };
const nested = process.env.QA_NESTED === '1';
if (nested) data.content = [{ type: 'FlexColumn', props: { id: 'nested-column', name: 'nested-column', content: data.content } }];
const content = () => nested ? data.content[0].props.content : data.content;
const catalog = [{ id: 'home', title: 'Home', slug: 'home', path: '/', published: true, sections: [] }];
await page.route('**/api/site-settings', route => route.fulfill({ json: { draft: { enabled: sharedNavigation, header: true, footer: true, brand: 'Studio', brandLink: '/', footerText: 'Footer', navigation: [], links: [] } } }));
await page.route('**/api/site?*', route => route.fulfill({ json: { data, page: catalog[0], pages: catalog, catalog, homepageId: 'home' } }));
await page.route('**/api/site', async route => { data = route.request().postDataJSON().data; await route.fulfill({ json: { catalog } }); });
await page.goto(`${origin}/fixtures?mode=studio`);
await page.locator('iframe').waitFor();
const frame = page.frames().find(f => f !== page.mainFrame());
const text = frame.locator('#paragraph-45 [contenteditable]');
await text.waitFor();
await text.click();
await text.evaluate(el => { window.originalEditable = el; window.originalCanvas = document.querySelector('.site-canvas'); });
await text.press('End');
const typingScroll = await frame.evaluate(() => window.scrollY);
for (const character of 'XYZ123') {
  await page.keyboard.type(character);
  await page.waitForTimeout(160);
  assert.equal(await text.evaluate(el => el === window.originalEditable && el === document.activeElement), true, 'each keystroke retains the focused editable');
  assert.ok(Math.abs(await frame.evaluate(() => window.scrollY) - typingScroll) < 5, 'typing preserves canvas scroll');
}
await page.waitForTimeout(1300);
console.log('typing', await text.innerText(), await text.evaluate(el => ({ same: el === window.originalEditable, canvas: document.querySelector('.site-canvas') === window.originalCanvas, scroll: window.scrollY })));
assert.match(await text.innerText(), /XYZ123/);
assert.equal(await text.evaluate(el => el === window.originalEditable), true);
assert.match(content()[45].props.text, /XYZ123/);
assert.deepEqual(errors, []);
await page.getByLabel('Text weight', { exact: true }).filter({ visible: true }).selectOption({ label: 'Bold' });
assert.equal(await frame.locator('#paragraph-45').evaluate(el => getComputedStyle(el).fontWeight), '700');
const scrollBefore = await frame.evaluate(() => document.scrollingElement.scrollTop);
console.log('before move', scrollBefore);
// Drag the actual block padding, away from the editable text portal.
const source = frame.locator('[data-puck-component="paragraph-45"]');
const target = frame.locator('[data-puck-component="paragraph-44"]');
await target.scrollIntoViewIfNeeded();
const dragScroll = await frame.evaluate(() => window.scrollY);
const from = await source.boundingBox();
const to = await target.boundingBox();
await page.mouse.move(from.x + from.width - 5, from.y + 5);
await page.mouse.down();
await page.waitForTimeout(250);
await page.mouse.move(from.x + from.width - 6, from.y - 10, { steps: 8 });
await page.mouse.move(to.x + to.width - 5, to.y + 5, { steps: 20 });
assert.ok(await frame.locator('[data-dnd-dragging]').count() > 0, 'pointer gesture starts an actual drag');
await page.mouse.up();
await page.waitForTimeout(1400);
console.log('after move', await frame.evaluate(() => document.scrollingElement.scrollTop), content().map(c => c.props.id).slice(42,48));
assert.equal(await frame.locator('.site-canvas').evaluate(el => el === window.originalCanvas), true);
assert.ok(await frame.evaluate(() => document.scrollingElement.scrollTop) > 0, 'lower-page drag preserves a scrolled viewport');
assert.equal(content()[44].props.id, 'paragraph-45');
assert.ok(Math.abs(await frame.evaluate(() => window.scrollY) - dragScroll) < 5, 'adjacent nested drag preserves canvas scroll');
const published = await browser.newPage();
await published.goto(`${origin}/fixtures?component=ParagraphBlock`);
await published.evaluate(() => sessionStorage.setItem('fixture-ParagraphBlock', JSON.stringify({ root: {}, content: [{ type: 'ParagraphBlock', props: { id: 'md', name: 'md', text: '**Bold** and [About](/about)\n\n- One\n- Two', fontWeight: '500', typographyFont: 'manrope', size: 'standard' } }] })));
await published.reload();
await published.locator('#md strong').waitFor();
assert.equal(await published.locator('#md a').getAttribute('href'), '/about');
assert.equal(await published.locator('#md li').count(), 2);
assert.equal(await published.locator('#md p').evaluate(el => getComputedStyle(el).fontWeight), '500');
assert.ok(Number(await published.locator('#md strong').evaluate(el => getComputedStyle(el).fontWeight)) > 500);
await published.screenshot({ path: '/tmp/editor-markdown-qa.png' });
assert.deepEqual(errors, []);
await browser.close();
console.log('PASS: inline identity, autosave, native weight, drag scroll, published Markdown');
